export function checkEmergency(userText) {
  if (!userText) return { ok: true };
  const text = String(userText).replace(/\s+/g, ' ').trim();
  for (const s of SIGNALS) {
    if (s.re.test(text)) {
      return { emergency: { signal: s.id, cond: s.cond } };
    }
  }
  return { ok: true };
}
